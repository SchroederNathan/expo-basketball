import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const output = join(root, 'src/screens/game/curtain');
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const manifest = JSON.parse(readFileSync(join(output, 'provenance.json'), 'utf8'));
const shader = readFileSync(join(output, 'curtain.wgsl'));
const generator = readFileSync(join(root, 'scripts/curtain/leather.rs'));
if (hash(shader) !== manifest.shaderSha256 || hash(generator) !== manifest.generatorSha256) {
  throw new Error('Recorded source checksum differs. Verify the local shader and upstream texture generator before updating provenance.');
}
const temporary = mkdtempSync(join(tmpdir(), 'lob-curtain-'));
try {
  execFileSync('rustc', ['--edition=2021', '-O', join(root, 'scripts/curtain/bake.rs'), '-o', join(temporary, 'bake')]);
  execFileSync(join(temporary, 'bake'), [join(temporary, 'leather.rgba')]);
  const leather = readFileSync(join(temporary, 'leather.rgba'));
  if (hash(leather) !== manifest.textureSha256 || leather.length !== 349524) {
    throw new Error('Original Rust texture bytes differ.');
  }
  const generated = `// Generated by scripts/curtain/generate.mjs.\nexport const curtainShader = ${JSON.stringify(shader.toString('utf8'))};\nexport const leatherBase64 = ${JSON.stringify(leather.toString('base64'))};\n`;
  const target = join(output, 'assets.generated.ts');
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== generated) throw new Error('Generated curtain assets are stale.');
  } else {
    writeFileSync(target, generated);
  }
  console.log(`Curtain verified. Recorded WGSL ${hash(shader)}, original Rust texture ${hash(leather)} (9 mips, ${leather.length} bytes).`);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
