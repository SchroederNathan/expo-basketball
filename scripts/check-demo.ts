import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fetchPlayer, fetchScoreboard, fetchSearch } from '../src/api/endpoints';
import { parseYmd, parseZone } from '../src/domain/dates';
import { isPlayerId } from '../src/domain/ids';
import { toSearchQuery } from '../src/domain/search';
import { DEMO_ENABLED } from '../src/demo/config';
import appConfig from '../app.config';

assert.ok(DEMO_ENABLED, 'Run with EXPO_PUBLIC_AGENT_DEMO=prizepicks-v1.');
globalThis.fetch = async () => { assert.fail('Demo mode must never call the live API.'); };
const date = parseYmd('20261026');
const zone = parseZone('America/Toronto');
const query = toSearchQuery('Avery');
assert.ok(date && zone && query);
const board = await fetchScoreboard({ league: 'nba', date, zone });
assert.equal(board.games[0]?.home.score, '108');
const results = await fetchSearch({ league: 'nba', query });
const id = results.results[0]?.id;
assert.ok(id && isPlayerId(id));
const player = await fetchPlayer({ ref: { league: 'nba', id }, zone });
assert.equal(player.player.stats[0]?.label, 'PTS');
await assert.rejects(fetchScoreboard({ league: 'wnba', date, zone }));
const abort = new AbortController();
abort.abort();
await assert.rejects(fetchScoreboard({ league: 'nba', date, zone }, { signal: abort.signal }));
const raw = JSON.parse(readFileSync('app.json', 'utf8')).expo;
const demo = appConfig({ config: raw, projectRoot: process.cwd(), staticConfigPath: 'app.json', packageJsonPath: 'package.json' });
assert.equal(demo.updates?.checkAutomatically, 'NEVER');
assert.deepEqual(demo.runtimeVersion, { policy: 'appVersion' });
assert.equal(demo.extra?.agentDemo?.sourceSha, execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim());
delete process.env.EXPO_PUBLIC_AGENT_DEMO;
const normal = appConfig({ config: raw, projectRoot: process.cwd(), staticConfigPath: 'app.json', packageJsonPath: 'package.json' });
assert.deepEqual(normal, raw, 'Normal app config and runtime policy remain unchanged.');
process.stdout.write('Demo API boundary, cancellation, source identity, and normal config checks passed.\n');
